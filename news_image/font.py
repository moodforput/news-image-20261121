FONT_CHARS = sorted(GLYPHS.keys())


def _gap(scale):
    """Gap in pixels between two adjacent characters at this scale."""
    return max(1, scale // 2)


def char_advance(scale):
    """Horizontal advance of one character, glyph plus gap."""
    return CHAR_WIDTH * scale + _gap(scale)


def text_width(text, scale):
    """Pixel width of text drawn at scale, without a trailing gap."""
    if not text:
        return 0
    return len(text) * char_advance(scale) - _gap(scale)


def text_height(scale):
    """Pixel height of one line of text at scale."""
    return CHAR_HEIGHT * scale


def draw_text(canvas, x, y, text, colour, scale=3):
    """Draw text with its top-left corner at (x, y). Returns width drawn."""
    cursor = x
    for char in text:
        rows = GLYPHS[char]  # raises KeyError for an uncovered character
        for row_index, row in enumerate(rows):
            for col in range(CHAR_WIDTH):
                if row & (1 << (CHAR_WIDTH - 1 - col)):
                    px = cursor + col * scale
                    py = y + row_index * scale
                    canvas.rect(px, py, scale, scale, colour)
        cursor += char_advance(scale)
    return text_width(text, scale)


def wrap_text(text, scale, max_width):
    """Greedy word wrap: lines that fit max_width, words never split."""
    words = text.split(" ")
    lines = []
    current = ""
    for word in words:
        trial = word if not current else current + " " + word
        if text_width(trial, scale) <= max_width:
            current = trial
        else:
            if current:
                lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines
